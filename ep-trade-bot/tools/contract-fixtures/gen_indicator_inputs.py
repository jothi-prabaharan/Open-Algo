"""Writes Core/Indicators/IndicatorInputs.cs from indicators.fixtures.json: for each openalgo.ta indicator, the series it reads and the history column each comes from.

Every case in the fixture records `series`, a map from the function's series parameter to the column it was fed, in signature order, which is exactly what OpenAlgo's
Flow indicator node resolves from the function's signature. Run it after re-recording the fixtures.
"""

import json
from pathlib import Path

here = Path(__file__).resolve().parent
d = json.loads((here / "indicators.fixtures.json").read_text(encoding="utf-8"))
inputs = {}
for c in d["cases"]:
    if c["indicator"] in inputs:
        continue
    inputs[c["indicator"]] = [(("open" if p == "open_prices" else p), col) for p, col in c["series"].items()]
lines = [
    "namespace EPTradeBot.Core.Indicators;",
    "",
    "/// <summary>Generated by tools/contract-fixtures/gen_indicator_inputs.py. The series each indicator reads, in the order of its signature, and the history column each is fed from.</summary>",
    "public static class IndicatorInputs",
    "{",
    "    public static readonly IReadOnlyDictionary<string, (string Series, string Column)[]> All = new Dictionary<string, (string, string)[]>(StringComparer.Ordinal)",
    "    {",
]
for name in sorted(inputs):
    pairs = ", ".join(f'("{p}", "{c}")' for p, c in inputs[name])
    lines.append(f'        ["{name}"] = [{pairs}],')
lines += ["    };", "}", ""]
(here.parents[1] / "src/EPTradeBot.Core/Indicators/IndicatorInputs.cs").write_text("\n".join(lines), encoding="utf-8")
print(len(inputs), "indicators;", sum(1 for v in inputs.values() if [p for p, _ in v] == ["data"]), "read a single series")
