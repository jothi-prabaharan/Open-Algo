"""Writes Core/Portfolio/CrisisPeriods.cs from portfolio.crisis.INDIA_CRISES so the dates are never retyped.

Run from the repository root: uv run python ep-trade-bot/tools/contract-fixtures/gen_crises.py
"""

import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
TMP = Path(tempfile.mkdtemp(prefix="oa-crises-"))
os.environ.setdefault("API_KEY_PEPPER", "0" * 64)
os.environ.setdefault("APP_KEY", "fixture-recorder-app-key")
os.environ.setdefault("FERNET_SALT", "ab" * 16)
os.environ.setdefault("DATABASE_URL", f"sqlite:///{TMP / 'openalgo.db'}")
os.environ.setdefault("LOG_DIR", str(TMP / "log"))

from portfolio.crisis import INDIA_CRISES  # noqa: E402


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


rows = ",\n".join(
    f"        new({q(c.key)}, {q(c.label)}, {q(c.start)}, {q(c.end)}, {q(c.note)}, {q(c.scope)})" for c in INDIA_CRISES
)
out = f"""// <auto-generated> by tools/contract-fixtures/gen_crises.py from OpenAlgo's portfolio.crisis.INDIA_CRISES. Do not edit by hand.
namespace EPTradeBot.Core.Portfolio;

/// <summary>A named stress window in Indian equities, shared by the portfolio and SIP back testers so both name the same events.</summary>
public sealed record CrisisPeriod(string Key, string Label, string Start, string End, string Note, string Scope)
{{
    public static readonly IReadOnlyList<CrisisPeriod> India =
    [
{rows},
    ];
}}
"""
(ROOT / "ep-trade-bot/src/EPTradeBot.Core/Portfolio/CrisisPeriods.cs").write_text(out, encoding="utf-8")
print(len(INDIA_CRISES), "periods")
